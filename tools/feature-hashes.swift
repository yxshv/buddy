import Foundation

// Build step (build.sh): prints a Swift file with the hash of every built-in feature folder, so the app
// trusts exactly the built-in features it was built with. Compiled together with Sources/FeatureHash.swift.
// Usage: feature-hashes <features dir>

let dir = URL(fileURLWithPath: CommandLine.arguments[1], isDirectory: true)
let folders = ((try? FileManager.default.contentsOfDirectory(at: dir, includingPropertiesForKeys: [.isDirectoryKey])) ?? [])
    .filter { (try? $0.resourceValues(forKeys: [.isDirectoryKey]))?.isDirectory == true }
    .sorted { $0.lastPathComponent < $1.lastPathComponent }
var lines: [String] = []
for folder in folders {
    guard let hash = FeatureHash.of(folder) else {
        FileHandle.standardError.write(Data("feature-hashes: \(folder.lastPathComponent) has a symbolic link or can't be read\n".utf8))
        exit(1)
    }
    lines.append("        \"\(folder.lastPathComponent)\": \"\(hash)\",")
}
print("""
// Generated by build.sh (tools/feature-hashes.swift). Don't edit.
enum BuiltinFeatures {
    static let hashes: [String: String] = [
\(lines.joined(separator: "\n"))
    ]
}
""")
